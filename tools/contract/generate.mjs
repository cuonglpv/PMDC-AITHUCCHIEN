// Generates everything that follows from the contracts and the DBML (docs/10-code-structure.md, section 9).
//   node tools/contract/generate.mjs           writes the files
//   node tools/contract/generate.mjs --check   fails if any of them is out of date
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const check = process.argv.includes('--check');
const claimsYaml = join(root, 'docs/api/claims-api.yaml');
const documentAiYaml = join(root, 'docs/api/document-ai.yaml');
const dbmlPath = join(root, 'docs/diagrams/claimlens.dbml');
const contractDoc = join(root, 'docs/07-api-contract.md');

const header = (source) =>
  `// <auto-generated>\n// Generated by tools/contract/generate.mjs from ${source}. Do not edit.\n// </auto-generated>\n`;

const pascal = (text) =>
  text
    .toLowerCase()
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

function readOperations() {
  const contract = parse(readFileSync(claimsYaml, 'utf8'));
  const operations = [];
  for (const [path, item] of Object.entries(contract.paths)) {
    for (const method of METHODS) {
      if (item[method]) {
        operations.push({ path, method: method.toUpperCase(), ...item[method] });
      }
    }
  }
  return { contract, operations };
}

function operationPolicies(operations) {
  const rows = operations.map((op) => {
    const policy = op['x-claimlens'];
    const roles = Object.entries(policy.roles ?? {})
      .map(([role, scope]) => `[StaffRole.${pascal(role)}] = ClaimScopeKind.${pascal(scope)}`)
      .join(', ');
    const states = policy.states ? policy.states.map((state) => `ClaimStatus.${pascal(state)}`).join(', ') : '';
    return (
      `        new("${op.operationId}", "${op.method}", "${op.path}", ` +
      `new Dictionary<StaffRole, ClaimScopeKind> { ${roles} }, ` +
      `${policy.states ? `[${states}]` : 'null'}, ` +
      `ReleaseKind.${pascal(policy.release)}, AuditKind.${pascal(policy.audit)}),`
    );
  });

  return `${header('docs/api/claims-api.yaml (x-claimlens)')}using ClaimLens.Api.Domain.Enums;

namespace ClaimLens.Api.Http;

public static partial class OperationPolicies
{
    public static readonly IReadOnlyList<OperationPolicy> All =
    [
${rows.join('\n')}
    ];
}
`;
}

function readEnums() {
  const dbml = readFileSync(dbmlPath, 'utf8').replace(/\r\n/g, '\n');
  return [...dbml.matchAll(/^Enum (\w+) \{\n([\s\S]*?)^\}/gm)].map((match) => ({
    name: match[1],
    values: match[2]
      .split('\n')
      .map((line) => line.trim().split(/\s+/)[0])
      .filter(Boolean),
  }));
}

// These three belong to the Rule Engine, which references nothing.
const ENGINE_ENUMS = new Set(['line_result', 'rule_type', 'limit_scope']);

function enumsFile(enums) {
  const blocks = enums
    .filter((item) => !ENGINE_ENUMS.has(item.name))
    .map(
      (item) =>
        `public enum ${pascal(item.name)}\n{\n${item.values.map((value) => `    ${pascal(value)},`).join('\n')}\n}`,
    );
  return `${header('docs/diagrams/claimlens.dbml')}namespace ClaimLens.Api.Domain.Enums;

${blocks.join('\n\n')}
`;
}

function enumMappingFile(enums) {
  const lines = enums.map((item) => {
    const translator = item.values.every((value) => value === value.toLowerCase()) ? 'LowerSnake' : 'UpperSnake';
    return `        npgsql.MapEnum<${pascal(item.name)}>("${item.name}", nameTranslator: ${translator});`;
  });
  return `${header('docs/diagrams/claimlens.dbml')}using ClaimLens.Api.Domain.Enums;
using ClaimLens.RuleEngine;
using Npgsql.EntityFrameworkCore.PostgreSQL.Infrastructure;

namespace ClaimLens.Api.Persistence;

public static partial class EnumMapping
{
    public static void MapAll(NpgsqlDbContextOptionsBuilder npgsql)
    {
${lines.join('\n')}
    }
}
`;
}

function roleMatrix(contract, operations) {
  const scope = { registered: 'own', assigned: 'assigned', any: 'any', all: 'all' };
  const roles = ['INTAKE_OFFICER', 'CLAIMS_REVIEWER', 'SENIOR_APPROVER', 'ADMINISTRATOR'];
  const sections = contract.tags.map((tag) => {
    const rows = operations
      .filter((op) => op.tags[0] === tag.name)
      .map((op) => {
        const policy = op['x-claimlens'];
        const isPublic = Object.keys(policy.roles ?? {}).length === 0;
        const cells = roles.map((role) => (isPublic ? 'public' : (scope[policy.roles[role]] ?? '')));
        const mark = policy.release === 'should' ? ' *Should*' : '';
        const body = cells.map((cell) => (cell ? ` ${cell} ` : '  ')).join('|');
        return `| \`${op.operationId}\`${mark} | \`${op.method} ${op.path}\` |${body}| ${policy.audit} |`;
      });
    return [
      `**${tag.name}**`,
      '',
      '| Operation | Request | Intake | Reviewer | Approver | Admin | Audit |',
      '|---|---|---|---|---|---|---|',
      ...rows,
    ].join('\n');
  });
  return sections.join('\n\n');
}

function withRoleMatrix(doc, matrix) {
  const start = '<!-- role-matrix:start -->';
  const end = '<!-- role-matrix:end -->';
  const before = doc.slice(0, doc.indexOf(start) + start.length);
  const after = doc.slice(doc.indexOf(end));
  return `${before}\n\n${matrix}\n\n${after}`;
}

function run(command, args) {
  // Windows needs the shell to find npx.cmd and uvx; the arguments here are all fixed paths.
  execFileSync(command, args, { cwd: root, stdio: ['ignore', 'ignore', 'pipe'], shell: process.platform === 'win32' });
}

function typescriptTypes(work) {
  const output = join(work, 'schema.d.ts');
  run('npx', ['--no-install', 'openapi-typescript', 'docs/api/claims-api.yaml', '-o', output]);
  return readFileSync(output, 'utf8');
}

function pydanticModels(work) {
  const output = join(work, 'models.py');
  run('uvx', [
    '--quiet',
    '--python',
    '3.12',
    // The generator formats with whichever ruff it finds, and only warns if there is none. Pinning it here makes the
    // output the same on every machine; this must match the ruff version in apps/document-ai/pyproject.toml.
    '--with',
    'ruff==0.17.3',
    '--from',
    'datamodel-code-generator==0.89.0',
    'datamodel-codegen',
    '--input',
    'docs/api/document-ai.yaml',
    '--input-file-type',
    'openapi',
    '--output-model-type',
    'pydantic_v2.BaseModel',
    '--target-python-version',
    '3.12',
    '--use-annotated',
    '--field-constraints',
    '--disable-timestamp',
    '--formatters',
    'ruff-format',
    'ruff-check',
    '--output',
    output,
  ]);
  return readFileSync(output, 'utf8').replace(/\r\n/g, '\n');
}

const { contract, operations } = readOperations();
const enums = readEnums();
const work = mkdtempSync(join(tmpdir(), 'claimlens-contract-'));

const outputs = {
  'apps/claims-api/src/ClaimLens.Api/Http/OperationPolicies.g.cs': operationPolicies(operations),
  'apps/claims-api/src/ClaimLens.Api/Domain/Enums/Enums.g.cs': enumsFile(enums),
  'apps/claims-api/src/ClaimLens.Api/Persistence/EnumMapping.g.cs': enumMappingFile(enums),
  'docs/07-api-contract.md': withRoleMatrix(
    readFileSync(contractDoc, 'utf8').replace(/\r\n/g, '\n'),
    roleMatrix(contract, operations),
  ),
  'apps/web/src/lib/api/schema.d.ts': typescriptTypes(work),
  'apps/document-ai/src/document_ai/contracts/models.py': pydanticModels(work),
};
rmSync(work, { recursive: true, force: true });

let stale = 0;
for (const [relative, content] of Object.entries(outputs)) {
  const path = join(root, relative);
  let current = null;
  try {
    current = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    current = null;
  }
  const same = current === content;
  if (check) {
    if (!same) {
      console.error(`Out of date: ${relative}. Run: npm run contract:generate`);
      stale += 1;
    }
    continue;
  }
  if (!same) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`Wrote ${relative}`);
  }
}

if (check && stale > 0) {
  process.exit(1);
}
console.log(check ? 'Generated files are current.' : `${operations.length} operations, ${enums.length} enums.`);
